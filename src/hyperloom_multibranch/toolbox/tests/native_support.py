"""A stand-in native component for the stage-4b tests: compiled, built out of process, laid and imported, with no compiler.

The component ``fakepkg`` keeps its Python in ``native/python/fakepkg`` and its "kernel" in ``native/src/act.cu``. Its
build script stands in for hipify and a compiler: it writes ``src/act.hip`` from the ``.cu`` the way hipify does (two lines
above it), fails like a compiler on an ``#error`` line of the ``.hip``, and otherwise "compiles" the extension by copying
an extension module of the interpreter running the tests (so the farm can really import it) with the hash of the ``.cu``
appended, which the loader ignores. A real compile is never run here.
"""

from __future__ import annotations

import functools
import importlib
import os
import sys
from dataclasses import dataclass
from pathlib import Path

from hyperloom.measure.compile import ComponentLayout, PackageBase
from hyperloom.measure.runner.native.recipes import NativeRecipe, Preflight
from hyperloom.measure.tests._recipes import write_tree

COMPONENT = "fakepkg"
ACT_CU = "native/src/act.cu"
BASE_CU = "__global__ void act() {}\n"
PY_FILE = f"native/python/{COMPONENT}/ops.py"
BASE_PY = "SCALE = 1\n"
FACTORY = f"{__name__}:stand_in_recipe"
LAYOUT = ComponentLayout(
    COMPONENT,
    f"native/python/{COMPONENT}",
    refuse=("*.so", "*.c", "*.cu", "*.hip", "*.h", "CMakeLists.txt", "setup.py"),
)

_BUILD = """\
import hashlib, pathlib, sys
cu, hip = pathlib.Path("src/act.cu"), pathlib.Path("src/act.hip")
hip.write_text("// !!! This is a file automatically generated by hipify!!!\\n#include \\"hip/hip_runtime.h\\"\\n" + cu.read_text())
for number, line in enumerate(hip.read_text().splitlines(), 1):
    if line.startswith("#error"):
        print(f"{pathlib.Path.cwd()}/src/act.hip:{number}:2: error: {line[7:]}")
        sys.exit(1)
out = pathlib.Path("python/fakepkg") / pathlib.Path(sys.argv[1]).name
out.write_bytes(pathlib.Path(sys.argv[1]).read_bytes() + hashlib.sha256(cu.read_bytes()).digest())
"""


#: Extension modules that load under another package name, in the order they are tried.
_STAND_INS = ("_crypt", "_cffi_backend", "yaml._yaml", "charset_normalizer.md")


@functools.cache
def extension() -> Path:
    """An extension module of this interpreter that loads on its own: the stand-in compiler's output."""
    for name in _STAND_INS:
        try:
            found = getattr(importlib.import_module(name), "__file__", None)
        except ImportError:
            continue
        if found and found.endswith(".so"):
            return Path(found)
    raise LookupError(f"none of {_STAND_INS} is an extension module of this interpreter")


def module_name() -> str:
    return f"{COMPONENT}.{extension().name.split('.', 1)[0]}"


def _preflight(scratch: Path, gfx_arch: str) -> Preflight:
    """No machine check; it records the names of the variables the build runner's child was given."""
    return Preflight(None, {"compiler": "stand-in", "variables": " ".join(sorted(os.environ))})


def stand_in_recipe() -> NativeRecipe:
    """The recipe the build runner's child imports by :data:`FACTORY`."""
    return NativeRecipe(
        component=COMPONENT,
        import_name=COMPONENT,
        version="fake/1",
        source_dir="native",
        package_dir="python",
        outputs=(f"{COMPONENT}/*.so",),
        command=("{python}", "build.py", str(extension())),
        budget_sec=120,
        max_jobs=1,
        max_output_bytes=64 * 1024 * 1024,
        preflight=_preflight,
    )


def compiled(cu: str) -> bytes:
    """What the stand-in compiler makes of ``cu``."""
    import hashlib

    return extension().read_bytes() + hashlib.sha256(cu.encode()).digest()


@dataclass(frozen=True)
class Image:
    """The image's site-packages with the unpatched ``fakepkg``, and an interpreter that finds it by default."""

    site: Path
    python: str

    def package(self) -> PackageBase:
        return PackageBase(COMPONENT, self.site / COMPONENT, COMPONENT, "1.0")


def image(root: Path) -> Image:
    site = write_tree(root / "site", {f"{COMPONENT}/__init__.py": "", f"{COMPONENT}/ops.py": BASE_PY})
    (site / COMPONENT / extension().name).write_bytes(compiled(BASE_CU))
    python = root / "python"
    python.write_text(
        f"#!{sys.executable}\n"
        "import os, sys\n"
        f"os.environ['PYTHONPATH'] = os.pathsep.join(filter(None, [os.environ.get('PYTHONPATH'), {str(site)!r}]))\n"
        "os.execv(sys.executable, [sys.executable, *[a for a in sys.argv[1:] if a != '-I']])\n"
    )
    python.chmod(0o755)
    return Image(site, str(python))


def upstream(root: Path) -> Path:
    """The pinned upstream checkout of ``fakepkg``."""
    return write_tree(
        root,
        {
            "native/build.py": _BUILD,
            "native/CMakeLists.txt": "project(fake)\n",
            ACT_CU: BASE_CU,
            PY_FILE: BASE_PY,
            f"native/python/{COMPONENT}/__init__.py": "",
        },
    )
