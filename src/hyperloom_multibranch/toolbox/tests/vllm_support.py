"""A stand-in vLLM for the stage-4c tests: vLLM's own recipe and rule-pack layout over a repository shaped like vLLM's.

The upstream checkout has vLLM's layout (``csrc/`` and the build definition at the top, the package in ``vllm/``). The
recipe is :func:`~hyperloom.measure.runner.native.recipes.vllm_recipe` as it is, its command included, with only the
machine preflight replaced: the checkout's ``setup.py`` stands in for vLLM's CMake build. Run as ``setup.py build_ext
--inplace``, it refuses an environment without the variables vLLM's ROCm build reads, writes ``csrc/cache_kernels.hip``
from the ``.cu`` the way hipify does, fails like a compiler on an ``#error`` line of the ``.hip``, and otherwise "compiles"
the extension beside the package (``vllm/<extension>``, as vLLM's build puts ``vllm/_C.abi3.so``) with
:mod:`native_support`'s stand-in compiler. A real compile is never run here.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path

from hyperloom.measure.compile import COMPONENT_LAYOUTS
from hyperloom.measure.runner.native.recipes import NativeRecipe, vllm_recipe
from hyperloom.measure.tests._recipes import write_tree
from hyperloom_multibranch.toolbox.tests import native_support

COMPONENT = "vllm"
ACT_CU = "csrc/cache_kernels.cu"
BASE_CU = native_support.BASE_CU
PY_FILE = "vllm/envs.py"
BASE_PY = native_support.BASE_PY
FACTORY = f"{__name__}:stand_in_recipe"
#: The rule pack's layout of vLLM, as a session reads it.
LAYOUT = COMPONENT_LAYOUTS[COMPONENT]
#: What the stand-in build requires of its environment: the variables vLLM's ROCm build reads, as the recipe sets them.
REQUIRED = {"PYTORCH_ROCM_ARCH": "gfx942", "ROCM_HOME": "/opt/rocm", "CUDA_HOME": "/opt/rocm", "MAX_JOBS": "8"}

_SETUP = """\
import hashlib, os, pathlib, sys
if sys.argv[1:] != ["build_ext", "--inplace"]:
    sys.exit(f"setup.py: unexpected arguments {{sys.argv[1:]}}")
wrong = {{name: os.environ.get(name) for name, value in {required!r}.items() if os.environ.get(name) != value}}
if wrong:
    sys.exit(f"setup.py: the build environment is not vLLM's ROCm build's: {{wrong}}")
cu, hip = pathlib.Path("csrc/cache_kernels.cu"), pathlib.Path("csrc/cache_kernels.hip")
hip.write_text("// !!! This is a file automatically generated by hipify!!!\\n#include \\"hip/hip_runtime.h\\"\\n" + cu.read_text())
for number, line in enumerate(hip.read_text().splitlines(), 1):
    if line.startswith("#error"):
        print(f"{{pathlib.Path.cwd()}}/csrc/cache_kernels.hip:{{number}}:2: error: {{line[7:]}}")
        sys.exit(1)
extension = pathlib.Path({extension!r})
(pathlib.Path("vllm") / extension.name).write_bytes(extension.read_bytes() + hashlib.sha256(cu.read_bytes()).digest())
"""


def stand_in_recipe() -> NativeRecipe:
    """vLLM's recipe with the stand-in preflight: what the build runner's child imports by :data:`FACTORY`."""
    return replace(vllm_recipe(), preflight=native_support.preflight)


def module_name() -> str:
    """The stand-in extension's module inside vLLM's package, as the farm imports it."""
    return f"{COMPONENT}.{native_support.extension().name.split('.', 1)[0]}"


def image(root: Path) -> native_support.Image:
    """The image's site-packages with the unpatched vLLM, its extension built from :data:`BASE_CU`."""
    return native_support.image(root, COMPONENT, {"envs.py": BASE_PY})


def upstream(root: Path) -> Path:
    """The pinned upstream checkout of vLLM: ``<sources>/vllm/<ref>``."""
    return write_tree(
        root,
        {
            "setup.py": _SETUP.format(required=REQUIRED, extension=str(native_support.extension())),
            "CMakeLists.txt": "project(vllm_extensions)\n",
            "cmake/utils.cmake": "# helpers\n",
            "cmake/hipify.py": "# hipify driver\n",
            ACT_CU: BASE_CU,
            "csrc/ops.h": "void act();\n",
            "vllm/__init__.py": "",
            PY_FILE: BASE_PY,
        },
    )
