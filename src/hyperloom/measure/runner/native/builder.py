COMPILE_ERROR = "compile_error"
_TREE = "tree"
_SOURCE_MODES = {EXECUTABLE: 0o700}
_SOURCE_MODE = 0o600
_WRITE_FLAGS = os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW | os.O_CLOEXEC
#: A compiler's diagnostic line (``file:line:col: error: ...``). The compile's output is kept only as its tails, and a
#: parallel build prints the failing file's error long before its tail (the other jobs' output and the build tool's
#: traceback follow), so the error lines are taken from the whole output first.
_COMPILER_ERROR = re.compile(r"^\S.*?:\d+(?::\d+)?: (?:fatal )?error: .*$", re.MULTILINE)
_MAX_ERRORS = 20
_MAX_ERROR_CHARS = 500
#: An error in a ``.hip`` file: ``(path, line, col, rest)``.
_HIP_ERROR = re.compile(r"^(\S.*?)\.hip:(\d+)((?::\d+)?)(: .*)$", re.DOTALL)
#: The lines torch's hipify puts above a ``.cu`` file's own when it writes the ``.hip`` (its breadcrumb, then the HIP
#: runtime include when the file has device code and no such include); every other change it makes keeps the lines.
_HIPIFY_BREADCRUMB = "// !!! This is a file automatically generated by hipify!!!"
_HIPIFY_INCLUDE = '#include "hip/hip_runtime.h"'


@dataclass(frozen=True)
class BuildMachine:
    """Where the outputs run and where they are built."""

    image_digest: str
    builder_image_digest: str
    gfx_arch: str
    python: str = sys.executable


@dataclass(frozen=True)
class BuildRequest:
    """One stack of one component: ``upstream`` is the checkout of ``stack.upstream_ref``; ``image_root`` is the image's
    directory that holds the installed package (``site-packages``), which ``recipe.package_dir`` stands for in the tree:
    outputs equal to its files are not stored."""

    recipe: NativeRecipe
    stack: ComponentPatches
    upstream: Path
    image_root: Path
    machine: BuildMachine


def plan(request: BuildRequest, blobs: BlobStore) -> tuple[BuildInputs, EnvRoot]:
    """The key's inputs and the changed native files, from the stack alone (nothing is compiled)."""
    recipe, machine = request.recipe, request.machine
    base_dir = Path(request.upstream) / recipe.source_dir
    root = apply_patch_stack(
        request.stack, recipe.layout(), PackageBase(recipe.import_name, base_dir, None, None), blobs
    )
    inputs = BuildInputs(
        machine.image_digest,
        machine.builder_image_digest,
        recipe.component,
        machine.gfx_arch,
        native_digest(root.entries, base_dir),
        recipe.version,
    )
    return inputs, root


def tree_dir(scratch: Path) -> Path:
    """Where :func:`compile_tree` builds below its scratch directory."""
    return Path(scratch) / _TREE


@dataclass(frozen=True)
class LaidTree:
    """A tree laid for one compile (:func:`lay_tree`): what :func:`compile_laid` needs, and nothing of the stack's.

    ``tracked`` is the upstream build directory (a ``.hip`` it holds is a source, not hipify's output), ``laid`` the
    paths the stack wrote over it; ``environment`` holds variables the planner chose for this compile, under the recipe's
    own (which win)."""

    recipe: NativeRecipe
    machine: BuildMachine
    tracked: Path
    image_root: Path
    laid: frozenset[str]
    environment: Mapping[str, str] = field(default_factory=dict)


def lay_tree(request: BuildRequest, root: EnvRoot, blobs: BlobStore, scratch: Path) -> LaidTree:
    """Copy the upstream build directory below ``scratch`` and lay ``root`` over it; nothing of the candidate runs."""
    recipe = request.recipe
    tracked = Path(request.upstream) / recipe.source_dir
    shutil.copytree(tracked, tree_dir(scratch), symlinks=True)
    _lay(tree_dir(scratch), root, blobs)
    laid = frozenset(entry.path for entry in root.entries if entry.op == "upsert")
    return LaidTree(recipe, request.machine, tracked, Path(request.image_root), laid)


def compile_tree(
    request: BuildRequest, root: EnvRoot, blobs: BlobStore, scratch: Path, *, against_image: bool = True
) -> Staged:
    """Compile the upstream build directory with ``root`` laid over it, and harvest its outputs (:func:`lay_tree`, then
    :func:`compile_laid`)."""
    return compile_laid(lay_tree(request, root, blobs, scratch), scratch, against_image=against_image)


def compile_laid(laid: LaidTree, scratch: Path, *, against_image: bool = True) -> Staged:
    """Compile the tree :func:`lay_tree` laid below ``scratch``, and harvest its outputs. This runs the candidate's code.

    With ``against_image`` false every output is kept, not only those that differ from the image's.

    Raises:
        BuildInfraError: When the preflight fails, the compile times out or is killed by a signal.
    """
    recipe, machine, tree = laid.recipe, laid.machine, tree_dir(scratch)
    checked = recipe.preflight(Path(scratch), machine.gfx_arch)
    if checked.problem is not None:
        raise BuildInfraError(f"the builder failed its preflight: {checked.problem}")
    toolchain = {**checked.toolchain, "gfx": machine.gfx_arch, "max_jobs": str(recipe.max_jobs)}
    started, cpu_before = time.monotonic(), _children_cpu_seconds()
    errors: list[str] = []
    result = run_argv(
        recipe.argv(machine.python),
        cwd=tree,
        env={**laid.environment, **recipe.environment(machine.gfx_arch, Path(scratch))},
        timeout_sec=recipe.budget_sec,
        run=_keeping_errors(errors, f"{tree}{os.sep}"),
    )
    timing = (_children_cpu_seconds() - cpu_before, time.monotonic() - started)
    errors = [_named_for_the_source(error, tree, laid.tracked, set(laid.laid)) for error in errors]
    log = "\n".join([*errors, result.stdout_tail, result.stderr_tail])
    if result.returncode < 0:
        raise BuildInfraError(f"the compile of {recipe.component} timed out or was killed (rc={result.returncode})")
    if result.returncode != 0:
        exited = f"{COMPILE_ERROR}: the compile exited {result.returncode}"
        return _failed(f"{exited}: {errors[0]}" if errors else exited, toolchain, timing, log, scratch)
    image = laid.image_root if against_image and recipe.against_image else None
    try:
        outputs = harvest(tree / recipe.package_dir, recipe.outputs, image, recipe.max_output_bytes, Path(scratch))
    except HarvestError as exc:
        return _failed(f"{COMPILE_ERROR}: {exc}", toolchain, timing, log, scratch)
    return Staged(READY, outputs, toolchain, timing[0], timing[1], log, Path(scratch))


def _keeping_errors(errors: list[str], tree_prefix: str) -> Callable[..., subprocess.CompletedProcess[str]]:
    """A ``subprocess.run`` in a session of its own (a timeout kills every process the compile started, see
    :mod:`.process_group`) that also collects the compiler's distinct error lines from the whole output, paths made
    relative to the tree."""

    def run(argv: list[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
        done = run_in_group(argv, **kwargs)
        for stream in (done.stdout or "", done.stderr or ""):
            for line in _COMPILER_ERROR.findall(stream):
                error = line.replace(tree_prefix, "")[:_MAX_ERROR_CHARS]
                if len(errors) < _MAX_ERRORS and error not in errors:
                    errors.append(error)
        return done

    return run


def _named_for_the_source(error: str, tree: Path, tracked: Path, laid: set[str]) -> str:
    """``error`` with the ``.cu`` file named in place of the ``.hip`` the build's hipify generated from it (the original
    in parentheses): the patch changed the ``.cu``. A ``.hip`` the upstream tree or the stack holds is a source itself,
    and one with no ``.cu`` beside it is left as it is."""
    match = _HIP_ERROR.match(error)
    if match is None:
        return error
    stem, line, col, rest = match.groups()
    if Path(stem).is_absolute() or ".." in Path(stem).parts:
        return error
    hip, cu = f"{stem}.hip", f"{stem}.cu"
    if hip in laid or os.path.lexists(tracked / hip) or not (tree / cu).is_file() or not (tree / hip).is_file():
        return error
    source_line = int(line) - _hipify_prologue(tree / hip, tree / cu)
    if source_line < 1:
        return error
    return f"{cu}:{source_line}{col} ({hip}:{line}{col}){rest}"


def _hipify_prologue(hip: Path, cu: Path) -> int:
    """How many lines hipify put above the ``.cu`` file's first line in the ``.hip``."""
    hip_head, cu_head = _first_lines(hip, 2), _first_lines(cu, 1)
    added = 1 if hip_head[:1] == [_HIPIFY_BREADCRUMB] else 0
    if hip_head[added : added + 1] == [_HIPIFY_INCLUDE] and cu_head != [_HIPIFY_INCLUDE]:
        added += 1
    return added


def _first_lines(path: Path, count: int) -> list[str]:
    with path.open(encoding="utf-8", errors="replace") as stream:
        return [line.rstrip("\r\n") for _, line in zip(range(count), stream)]


def _failed(failure: str, toolchain: dict[str, str], timing: tuple[float, float], log: str, scratch: Path) -> Staged:
    return Staged(FAILED, (), toolchain, timing[0], timing[1], log, Path(scratch), failure=failure)


def _children_cpu_seconds() -> float:
    usage = resource.getrusage(resource.RUSAGE_CHILDREN)
    return usage.ru_utime + usage.ru_stime


def _lay(tree: Path, root: EnvRoot, blobs: BlobStore) -> None:
    """Lay the stack's changed files over the copied tree: each written new (a symlink there is replaced, never
    followed), or removed."""
    for entry in root.entries:
        target = tree / entry.path
        if os.path.lexists(target):
            target.unlink()
        if entry.op != "upsert":
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        descriptor = os.open(target, _WRITE_FLAGS, _SOURCE_MODES.get(entry.mode or "", _SOURCE_MODE))
        with os.fdopen(descriptor, "wb") as out:
            out.write(blobs.get(entry.blob or ""))
