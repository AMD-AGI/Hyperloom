# Bootstrap the BYOI toolchain inside the RayJob head pod.
#
# Submitted by ``hyperloom.inference_optimizer.multi_node bootstrap`` via the Ray
# Dashboard REST ``/api/jobs/`` endpoint, which means this script runs
# INSIDE the RayJob head pod, not in the Claw sandbox.
#
# Idempotent: a marker file at ``$BOOTSTRAP_MARKER`` short-circuits the
# whole script on subsequent calls. To force a re-run pass ``--force`` or
# ``unset`` the marker first.
#
# Renders ``/etc/profile.d/hyperloom-env.sh`` with the framework venv PATH
# only, so every later REST job that does ``source /etc/profile.d/hyperloom-env.sh``
# picks up the same PATH. Credentials are deliberately NOT written (the file is
# world-readable); later jobs inherit *_API_KEY / *_BASE_URL from the container env.

set -euo pipefail

BOOTSTRAP_MARKER="${BOOTSTRAP_MARKER:-/opt/hyperloom/.bootstrap_done}"
# Empty unless the operator pins a venv root explicitly; resolved below so the
# script works on both venv images (/opt/venv) and system-python images.
HYPERLOOM_VENV="${HYPERLOOM_VENV:-}"
LOG_DIR="${LOG_DIR:-/var/log/hyperloom}"
ENV_FILE="${ENV_FILE:-/etc/profile.d/hyperloom-env.sh}"

FORCE=0
for arg in "$@"; do
    case "$arg" in
        --force) FORCE=1 ;;
        *) echo "bootstrap.sh: unknown arg: $arg" >&2; exit 2 ;;
    esac
done

mkdir -p "$LOG_DIR" "$(dirname "$BOOTSTRAP_MARKER")"

if [ "$FORCE" -eq 0 ] && [ -f "$BOOTSTRAP_MARKER" ]; then
    echo "bootstrap.sh: marker $BOOTSTRAP_MARKER present; skipping. Pass --force to re-run."
    exit 0
fi

# --- 1. Resolve the framework Python. Older BYOI images ship a venv at
#        /opt/venv; newer images expose the framework on the system python3.
#        Honor an explicit HYPERLOOM_VENV override, else prefer /opt/venv,
#        else fall back to system python3 (venv root = <dir>/.. so the
#        "$HYPERLOOM_VENV/bin/python3" contract still holds, e.g. /usr).
if [ -z "$HYPERLOOM_VENV" ]; then
    if [ -x /opt/venv/bin/python3 ]; then
        HYPERLOOM_VENV=/opt/venv
    else
        _sys_py="$(command -v python3 || true)"
        if [ -n "$_sys_py" ]; then
            HYPERLOOM_VENV="$(dirname "$(dirname "$_sys_py")")"
        fi
    fi
fi

if [ -z "$HYPERLOOM_VENV" ] || [ ! -x "$HYPERLOOM_VENV/bin/python3" ]; then
    echo "bootstrap.sh: ERROR — no framework python3 found." >&2
    echo "             looked for /opt/venv/bin/python3 and system python3;" >&2
    echo "             set HYPERLOOM_VENV to the venv root (<root>/bin/python3)." >&2
    exit 1
fi
echo "bootstrap.sh: framework python -> $HYPERLOOM_VENV/bin/python3"

# --- 2. Render /etc/profile.d/hyperloom-env.sh with the venv PATH only.
#        Credentials are intentionally NOT written here: this file is
#        world-readable (0644) and any pod shell (incl. the untrusted
#        specialist Bash) could read secrets from it. Later Ray Dashboard
#        REST jobs run as children of the head-pod container and already
#        inherit *_API_KEY / *_BASE_URL from the container env, so the
#        profile.d re-export is redundant for credentials and only needed
#        for the framework venv PATH.
echo "bootstrap.sh: writing $ENV_FILE (PATH only; no credentials)"
{
    echo "# Generated by hyperloom.inference_optimizer.multi_node bootstrap.sh — DO NOT EDIT."
    echo "export PATH=\"$HYPERLOOM_VENV/bin:\${PATH}\""
} > "$ENV_FILE"
chmod 0644 "$ENV_FILE"

# --- 3. Mark done.
date -u +"%Y-%m-%dT%H:%M:%SZ" > "$BOOTSTRAP_MARKER"
echo "bootstrap.sh: OK ($BOOTSTRAP_MARKER)"
