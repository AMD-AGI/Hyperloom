#!/usr/bin/env python3
"""Render a pack's roadmap.yaml into the knowledge/*.md the agent actually reads.

WHY THIS EXISTS. arbor/pack/render.py renders `knowledge/*.md` and the flat
`constraints:` list; it does not know about roadmap.yaml (that is Part 2 of the
hyperloom plan, unimplemented). So the roadmap has to reach the agent as
markdown. Copying it by hand would create two sources of truth that drift --
which is precisely the failure the structured roadmap exists to prevent. This
script makes the markdown DERIVED: regenerate it, never edit it.

The "how to read this" preamble is GENERATED from the grades actually present,
so it cannot claim a discipline the file does not keep.

    python3 scripts/pack/render_roadmap.py packs/<pack>/roadmap.yaml \
        > packs/<pack>/knowledge/roadmap.md
"""
from __future__ import annotations

import collections
import sys

import yaml

GRADE_GLOSS = {
    "reported": (
        "Someone else's system -- a different framework, GPU, or concurrency. "
        "It tells you a direction is real and roughly how big it was FOR THEM. "
        "It is a LEAD. Quoting it as your expected result is a claim you have "
        "not earned."
    ),
    "inferred": (
        "Read from source ON THIS STACK, with a file:line. It tells you the "
        "code path exists and what it does. It is not a measurement."
    ),
    "measured": (
        "Measured on THIS node, with an instrument and an artifact. This is "
        "the only grade that may price an item."
    ),
}


def _evidence_line(e: dict) -> str:
    grade = e.get("grade", "?")
    bits = []
    if e.get("source"):
        bits.append(str(e["source"]))
    if e.get("system"):
        bits.append(f"system: {e['system']}")
    if e.get("instrument"):
        bits.append(f"instrument: {e['instrument']}")
    if e.get("artifact"):
        bits.append(f"artifact: {e['artifact']}")
    if e.get("numbers"):
        bits.append(str(e["numbers"]))
    if e.get("note"):
        bits.append(str(e["note"]))
    return f"  - **{grade}** -- " + "; ".join(bits)


def render(doc: dict) -> str:
    sections = doc["sections"]
    items = doc["items"]
    grades = collections.Counter(
        e["grade"] for it in items for e in it.get("evidence", [])
    )

    out: list[str] = ["# THE ROADMAP", ""]
    out.append(
        "Generated from `roadmap.yaml` by `scripts/pack/render_roadmap.py`. "
        "Do not edit this file; edit the YAML and regenerate."
    )
    out.append("")
    out.append("## How to read it")
    out.append("")
    out.append(
        "Every item carries graded evidence. The grade is the whole point, and "
        f"this roadmap currently holds "
        + ", ".join(f"{n} {g}" for g, n in sorted(grades.items()))
        + "."
    )
    out.append("")
    for g in ("reported", "inferred", "measured"):
        if grades.get(g):
            out.append(f"- **{g}** ({grades[g]}) -- {GRADE_GLOSS[g]}")
    out.append("")
    out.append(
        "An item carrying ONLY `reported` evidence has not been sized here. "
        "Size it before you build it, and record the gap between the reported "
        "figure and your own -- that gap is itself a finding. Cite the item ID "
        "in your DONE line and in your ledger record ids."
    )
    out.append("")

    # A standing warning has to survive the render, or it protects nothing.
    if doc.get("warning"):
        out.append("## Standing warning")
        out.append("")
        out.append(doc["warning"].rstrip())
        out.append("")

    by_section: dict[str, list[dict]] = collections.defaultdict(list)
    for it in items:
        by_section[it["section"]].append(it)

    for key, title in sections.items():
        rows = by_section.get(key, [])
        if not rows:
            continue
        out.append(f"## {key} -- {title}")
        out.append("")
        for it in rows:
            head = f"### [{it['id']}] {it['title']}"
            flags = []
            if it.get("status") and it["status"] != "open":
                flags.append(it["status"].upper())
            if it.get("foundation"):
                flags.append("FOUNDATION")
            if it.get("gates"):
                flags.append("gates " + ", ".join(it["gates"]))
            if flags:
                head += "   _(" + "; ".join(flags) + ")_"
            out.append(head)
            out.append("")
            if it.get("body"):
                out.append(it["body"].rstrip())
                out.append("")
            ev = it.get("evidence") or []
            if ev:
                out.append("Evidence:")
                for e in ev:
                    out.append(_evidence_line(e))
                out.append("")
            else:
                out.append("Evidence: NONE RECORDED -- treat as a hunch.")
                out.append("")
    return "\n".join(out).rstrip() + "\n"


if __name__ == "__main__":
    sys.stdout.write(render(yaml.safe_load(open(sys.argv[1]))))
