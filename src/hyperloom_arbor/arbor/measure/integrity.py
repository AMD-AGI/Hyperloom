"""SHA-pinning and edit-scope enforcement.

Pin validator files at campaign start. Every gate checks they haven't moved.
"""

from __future__ import annotations

import hashlib
from dataclasses import dataclass
from pathlib import Path


def file_digest(path: str | Path) -> str:
    """SHA-256 of a file. Missing file returns ``"<absent>"``."""
    p = Path(path)
    if not p.exists():
        return "<absent>"
    return hashlib.sha256(p.read_bytes()).hexdigest()


def snapshot_digests(container: str, paths: list[str]) -> dict[str, str]:
    """Hash files inside a Docker container via ``sha256sum``.

    Directory paths are expanded to their contained files so that
    ``protected: [validator/]`` correctly pins every file under that directory.
    """
    from arbor.execute.workspace import run_in  # the host too, for "@host"
    if not paths:
        return {}

    # Expand directories to individual files inside the container
    file_paths: list[str] = []
    for p in paths:
        p = p.rstrip("/")
        # Never pin __pycache__. A .pyc is regenerated by the interpreter at
        # import time, spontaneously and with no source change, so pinning one
        # turns an ordinary import into "validator integrity check failed" and
        # costs an iteration. The dsv41flash campaign pinned 12 files, one of
        # them a .pyc, and carried that landmine for the whole run.
        r = run_in(container, ["find", p,
                               "-name", "__pycache__", "-prune", "-o",
                               "-name", "*.pyc", "-prune", "-o",
                               "-type", "f", "-print"],
                   capture_output=True, text=True)
        if r.returncode == 0 and r.stdout.strip():
            file_paths.extend(r.stdout.strip().splitlines())
        else:
            file_paths.append(p)  # not a directory or not found — hash as-is

    if not file_paths:
        return {}

    r = run_in(container, ["sha256sum", *file_paths], capture_output=True, text=True)
    digests = {}
    for line in r.stdout.strip().splitlines():
        parts = line.split(None, 1)
        if len(parts) == 2:
            digests[parts[1]] = parts[0]
    missing = [p for p in file_paths if p not in digests]
    if missing:
        raise RuntimeError(
            f"Validator files not found in container '{container}': {missing}. "
            "Check that workspace_root is correct and the container is running."
        )
    return digests


@dataclass(frozen=True)
class IntegrityResult:
    ok: bool
    changed: tuple[str, ...]
    reason: str


def verify_unchanged(
    baseline: dict[str, str], current: dict[str, str]
) -> IntegrityResult:
    """Every protected file's hash must match the campaign-start baseline."""
    changed = tuple(sorted(p for p, h in baseline.items() if current.get(p) != h))
    if changed:
        return IntegrityResult(
            False,
            changed,
            f"validator files changed: {', '.join(changed)}",
        )
    return IntegrityResult(True, (), "validator intact")


@dataclass(frozen=True)
class ScopeResult:
    ok: bool
    offending: tuple[str, ...]
    reason: str


def edit_scope_ok(
    changed_files: list[str],
    *,
    allowed: list[str],
    protected: list[str] | None = None,
) -> ScopeResult:
    """Every changed file must be under ``allowed`` and not under ``protected``."""
    protected = protected or []

    def _under(path: str, roots: list[str]) -> bool:
        for r in roots:
            r = r.rstrip("/")
            if path == r or path.startswith(r + "/"):
                return True
        return False

    offending = tuple(
        f
        for f in changed_files
        if _under(f, protected) or not _under(f, allowed)
    )
    if offending:
        return ScopeResult(
            False,
            offending,
            f"edits outside allowed scope: {', '.join(offending)}",
        )
    return ScopeResult(True, (), "edits in scope")
