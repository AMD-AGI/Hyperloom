"""A command's parameters as one JSON or YAML document (``--payload FILE``), and the schema of every command's.

The payload holds what the command's flags take, nothing more::

    python3 -m arbor run --payload run.yaml          # the command on the line, its parameters in the file
    python3 -m arbor --payload run.yaml              # the command in the file (``command: run``)
    python3 -m arbor run --payload - < run.json      # from stdin
    python3 -m arbor.directions --payload split.yaml # ``action: generate`` or ``split``
    python3 -m arbor schema [<command>]              # the JSON Schema; ``--markdown`` for the tables

    arbor_payload: 1                # the format's version: required
    command: run                    # required unless the command line names it; must match when both do
    config: /work/b01/config.json
    review_gate: false              # true: --review-gate, false: --no-review-gate, null or absent: the default

The rules:

- A key is the parameter's name: argparse's ``dest``, the long flag without ``--`` and with ``_`` for ``-``. A
  positional or a sub-command is a key too (``action``, ``cmd``), and the sub-command's parameters sit beside it.
- A value has its parameter's exact JSON type: ``"3"`` for an integer is refused, not converted.
- Strict: an unknown key, a hidden parameter, another command's or another action's key, or a wrong type exits 2
  and names the key. A payload never drops a key.
- The payload stands where the flags stand: a parameter wins over its environment variable, which wins over the
  config's key, as for flags. A flag on the same command line wins over the payload's key; two sides of one
  exclusive pair are refused.
- ``run`` with ``dry_run: true`` is ``run --dry-run``, which admits the dry run's own ``seed``.
- Relative paths resolve against the working directory, as on the command line. ``config`` is a path.

The payload becomes argv, and the command's own parser parses it, so the flags and the payload cannot disagree on a
default, a choice or a required parameter. The schema is generated from the same parsers, and so are
``docs/schema/arbor-cli-payload.schema.json`` and ``docs/cli.md`` (a test fails when they are stale):
``python3 -m arbor schema --write``.

A campaign's start records how it was asked for in ``<session>/invocation.json``: the command, its effective
parameters, which came from the payload and which from the command line, the payload's sha256, Arbor's version.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

#: The payload format's version: ``arbor_payload`` in every payload. Raised only when an old caller would break.
VERSION = 1
SCHEMA_ID = f"arbor-cli-payload/{VERSION}"
FORMATS = ("json", "yaml")
VERSION_KEY, COMMAND_KEY = "arbor_payload", "command"
FLAG = "--payload"
DRY_RUN = "dry_run"
#: <session>/: how the campaign's latest start was asked for.
RECORD = "invocation.json"
#: The commands a payload drives, in the usage's order. ``directions`` is ``python3 -m arbor.directions``'s
#: ``generate`` and ``split``, the map step a host runs; its ``check`` parses its own arguments and is not one.
COMMANDS = ("run", "master", "worker", "review", "conflicts", "iterate", "version", "directions")
DIRECTIONS_ACTIONS = ("generate", "split")

ROOT = Path(__file__).resolve().parent.parent.parent
SCHEMA_FILE = ROOT / "docs" / "schema" / "arbor-cli-payload.schema.json"
DOC_FILE = ROOT / "docs" / "cli.md"
DOC_BEGIN = "<!-- generated by `python3 -m arbor schema --write`: do not edit below -->"

#: Defaults the schema states in words: they depend on the machine or the environment.
DEFAULT_WORDS = {("run", "split"): "loop, or ARBOR_SPLIT when set", ("conflicts", "root"): "this checkout"}

#: The last expansion in this process, for :func:`record`.
INVOKED: dict | None = None


class PayloadError(ValueError):
    """A payload Arbor refuses; the message names the key and what the command takes."""


# ── the commands' parsers ─────────────────────────────────────────────────────────────────────────────────────────

def parser(command: str, *, dry_run: bool = False, action: str | None = None) -> argparse.ArgumentParser:
    """The argparse parser of ``command``, built as the command builds it, without parsing anything."""
    if command in ("run", "master", "worker"):
        if command == "run" and dry_run:
            from arbor import dry_run as _dry
            return _dry.parser()
        from arbor import driver
        return driver.parser(f"arbor {command}")
    if command == "review":
        from arbor import review
        return review.parser()
    if command == "conflicts":
        from arbor import conflicts
        return conflicts.parser()
    if command == "iterate":
        from arbor.cli import iterate
        return iterate.parser()
    if command == "version":
        from arbor import version
        return version.parser()
    if command == "directions":
        if action == "generate":
            from arbor import mapgen
            return mapgen.parser()
        if action == "split":
            from arbor import directions
            return directions.split_parser()
        raise PayloadError(f"directions: `action` must be one of {', '.join(DIRECTIONS_ACTIONS)}, not {action!r}")
    raise PayloadError(f"unknown command {command!r}: a payload drives one of {', '.join(COMMANDS)}")


def _visible(p: argparse.ArgumentParser) -> list[argparse.Action]:
    return [a for a in p._actions if not isinstance(a, argparse._HelpAction) and a.help != argparse.SUPPRESS]


def _subparsers(p: argparse.ArgumentParser) -> argparse._SubParsersAction | None:
    return next((a for a in _visible(p) if isinstance(a, argparse._SubParsersAction)), None)


def _is_flag(a: argparse.Action) -> bool:
    return isinstance(a, (argparse._StoreTrueAction, argparse._StoreFalseAction))


def _kind(a: argparse.Action) -> str:
    if _is_flag(a):
        return "boolean"
    if a.type is int:
        return "integer"
    if a.type is float:
        return "number"
    return "string"


def _long(a: argparse.Action) -> str:
    return next((s for s in a.option_strings if s.startswith("--")), a.option_strings[0])


# ── reading a payload ─────────────────────────────────────────────────────────────────────────────────────────────

def split_argv(argv: list[str]) -> tuple[str | None, list[str]]:
    """``--payload FILE`` (or ``--payload=FILE``) out of argv: the file, and the rest."""
    path, rest, i = None, [], 0
    while i < len(argv):
        a = argv[i]
        if a == FLAG or a.startswith(FLAG + "="):
            if path is not None:
                raise PayloadError(f"{FLAG} given twice")
            if a == FLAG:
                if i + 1 >= len(argv):
                    raise PayloadError(f"{FLAG} needs a file (or - for stdin)")
                path, i = argv[i + 1], i + 2
                continue
            path = a.split("=", 1)[1]
        else:
            rest.append(a)
        i += 1
    return path, rest


def load(path: str) -> tuple[dict, str]:
    """The payload at ``path`` (``-``: stdin), JSON or YAML, and its sha256."""
    where = "the payload on stdin" if path == "-" else path
    try:
        text = sys.stdin.read() if path == "-" else Path(path).read_text(encoding="utf-8")
    except OSError as exc:
        raise PayloadError(f"cannot read {where}: {exc}") from None
    try:
        doc = json.loads(text)
    except ValueError:
        import yaml
        try:
            doc = yaml.safe_load(text)
        except yaml.YAMLError as exc:
            raise PayloadError(f"{where} is neither JSON nor YAML: {exc}") from None
    if not isinstance(doc, dict):
        raise PayloadError(f"{where} must be a mapping of parameters, not {type(doc).__name__}")
    return doc, hashlib.sha256(text.encode("utf-8")).hexdigest()


def _value(command: str, dest: str, a: argparse.Action, value) -> str:
    kind = _kind(a)
    ok = {"integer": isinstance(value, int) and not isinstance(value, bool),
          "number": isinstance(value, (int, float)) and not isinstance(value, bool),
          "string": isinstance(value, str)}[kind]
    if not ok:
        raise PayloadError(f"{command}: `{dest}` takes {'a' if kind != 'integer' else 'an'} {kind}, "
                           f"not {type(value).__name__} {value!r}")
    if a.choices and value not in a.choices:
        raise PayloadError(f"{command}: `{dest}` must be one of {', '.join(map(str, a.choices))}, not {value!r}")
    return str(value)


def to_argv(p: argparse.ArgumentParser, params: dict, command: str) -> list[str]:
    """``params`` as argv for ``p``: options as ``--flag=value``, then positionals in the parser's order, then a
    sub-command and its own. A null value is the default (nothing on the line)."""
    sub = _subparsers(p)
    actions = [a for a in _visible(p) if a is not sub]
    by_dest: dict[str, list[argparse.Action]] = {}
    for a in actions:
        by_dest.setdefault(a.dest, []).append(a)
    sub_parser, sub_keys = None, set()
    if sub is not None:
        choice = params.get(sub.dest)
        if choice not in sub.choices:
            raise PayloadError(f"{command}: `{sub.dest}` must be one of {', '.join(sub.choices)}, not {choice!r}")
        sub_parser = sub.choices[choice]
        sub_keys = {a.dest for a in _visible(sub_parser)}
    known = set(by_dest) | ({sub.dest} if sub else set()) | sub_keys
    unknown = [k for k in params if k not in known]
    if unknown:
        hint = (f"; `{DRY_RUN}: true` admits {', '.join(unknown)}"
                if command == "run" and set(unknown) <= {"seed"} else "")
        raise PayloadError(f"{command}: unknown key{'s' if len(unknown) > 1 else ''} "
                           f"{', '.join(f'`{k}`' for k in unknown)}; it takes {', '.join(sorted(known))}{hint}")
    options, positionals = [], []
    for dest, acts in by_dest.items():
        if dest not in params:
            continue
        value = params[dest]
        if value is None:
            continue
        if all(_is_flag(a) for a in acts):
            if not isinstance(value, bool):
                raise PayloadError(f"{command}: `{dest}` takes a boolean, not {type(value).__name__} {value!r}")
            options += [_long(a) for a in acts if a.const == value][:1]
            continue
        a = acts[0]
        text = _value(command, dest, a, value)
        if a.option_strings:
            options.append(f"{_long(a)}={text}")
        else:
            positionals.append(text)
    argv = options + positionals
    if sub_parser is not None:
        argv += [params[sub.dest]] + to_argv(sub_parser, {k: v for k, v in params.items() if k in sub_keys},
                                             f"{command} {params[sub.dest]}")
    return argv


def expand(argv: list[str]) -> list[str]:
    """argv with its ``--payload`` replaced by the payload's flags: ``[command, *flags]``. Flags already on the line
    come after, so they win. Raises :class:`PayloadError` for a payload Arbor refuses."""
    global INVOKED
    path, rest = split_argv(argv)
    if path is None:
        return list(argv)
    doc, sha = load(path)
    if doc.get(VERSION_KEY) != VERSION:
        raise PayloadError(f"`{VERSION_KEY}: {VERSION}` is required: this Arbor reads payload version {VERSION}"
                           + (f", not {doc[VERSION_KEY]!r}" if VERSION_KEY in doc else ""))
    named = rest.pop(0) if rest and not rest[0].startswith("-") else None
    asked = doc.get(COMMAND_KEY)
    if named and asked and named != asked:
        raise PayloadError(f"the command line runs `{named}`, the payload's `{COMMAND_KEY}` is `{asked}`")
    command = named or asked
    if not command:
        raise PayloadError(f"no command: name it on the command line or as `{COMMAND_KEY}:` in the payload")
    if command not in COMMANDS:
        raise PayloadError(f"unknown command {command!r}: a payload drives one of {', '.join(COMMANDS)}")
    params = {k: v for k, v in doc.items() if k not in (VERSION_KEY, COMMAND_KEY)}
    head = [command]
    if command == "run":
        dry = params.pop(DRY_RUN, None)
        if dry is not None and not isinstance(dry, bool):
            raise PayloadError(f"run: `{DRY_RUN}` takes a boolean, not {type(dry).__name__} {dry!r}")
        dry = bool(dry) or "--dry-run" in rest
        rest = [a for a in rest if a != "--dry-run"]
        if dry:
            head.append("--dry-run")
        p = parser("run", dry_run=dry)
    elif command == "directions":
        action = params.pop("action", None)
        if rest and rest[0] in DIRECTIONS_ACTIONS:
            on_line = rest.pop(0)
            if action and action != on_line:
                raise PayloadError(f"the command line runs `directions {on_line}`, the payload's `action` is "
                                   f"`{action}`")
            action = action or on_line
        p = parser("directions", action=action)
        head.append(action)
    else:
        p = parser(command)
    flags = to_argv(p, params, command)
    INVOKED = {"command": command, "argv": [*head[1:], *flags, *rest],
               "payload": {"path": "-" if path == "-" else str(Path(path).resolve()), "sha256": sha,
                           "keys": sorted(params)},
               "flags": rest}
    return [*head, *flags, *rest]


def run_expanded(argv: list[str], prog: str = "arbor") -> list[str] | int:
    """:func:`expand` for a command's entry point: the expanded argv, or 2 after saying why it is refused."""
    try:
        return expand(argv)
    except PayloadError as exc:
        print(f"{prog}: {FLAG}: {exc}", file=sys.stderr)
        return 2


# ── the record ────────────────────────────────────────────────────────────────────────────────────────────────────

def record(session_dir: Path, args: argparse.Namespace, command: str = "run") -> dict:
    """Write ``<session>/invocation.json``: how this start was asked for. Without a payload, its argv."""
    from arbor import version
    params = {k: (str(v) if isinstance(v, Path) else v) for k, v in sorted(vars(args).items())
              if not k.startswith("_") and k != "started"}
    inv = INVOKED or {"command": command, "argv": sys.argv[1:], "payload": None, "flags": sys.argv[1:]}
    given = set((inv.get("payload") or {}).get("keys", []))
    doc = {"command": inv["command"], "params": params,
           "from_payload": sorted(k for k in params if k in given),
           "argv": inv["argv"], "payload": inv.get("payload"), "arbor": version.VERSION,
           "ts": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}
    path = Path(session_dir) / RECORD
    path.write_text(json.dumps(doc, indent=1, default=str) + "\n")
    return doc


# ── the schema ────────────────────────────────────────────────────────────────────────────────────────────────────

def _prop(command: str, a: argparse.Action) -> dict:
    s: dict = {"type": _kind(a)}
    if a.choices and not isinstance(a, argparse._SubParsersAction):
        s["enum"] = list(a.choices)
    words = DEFAULT_WORDS.get((command, a.dest))
    if words:
        s["$comment"] = f"default: {words}"
    elif a.default is not None and a.default != "" and not isinstance(a.default, Path):
        s["default"] = a.default
    if a.help:
        s["description"] = " ".join(str(a.help).split())
    return s


def _params(command: str, p: argparse.ArgumentParser) -> tuple[dict, list[str], list[tuple]]:
    """The parser's keys: properties, required keys, and its sub-commands' (name, properties, required)."""
    props, required, branches = {}, [], []
    seen: dict[str, list[argparse.Action]] = {}
    for a in _visible(p):
        if isinstance(a, argparse._SubParsersAction):
            props[a.dest] = {"enum": list(a.choices), "description": f"the {command} action"}
            required.append(a.dest)
            for name, sp in a.choices.items():
                sprops, sreq, _ = _params(command, sp)
                branches.append((name, sprops, sreq))
            continue
        seen.setdefault(a.dest, []).append(a)
    for dest, acts in seen.items():
        if len(acts) > 1 and all(_is_flag(a) for a in acts):   # an exclusive pair: one tri-state key
            on = next(a for a in acts if a.const is True)
            off = next(a for a in acts if a.const is False)
            props[dest] = {"type": ["boolean", "null"],
                           "description": f"true: {_long(on)}, {' '.join(str(on.help).split())}; false: "
                                          f"{_long(off)}, {' '.join(str(off.help).split())}; null or absent: the "
                                          f"default"}
        else:
            props[dest] = _prop(command, acts[0])
        if any(a.required or not a.option_strings for a in acts):
            required.append(dest)
    return props, required, branches


def _command_schema(command: str, p: argparse.ArgumentParser, dry: argparse.ArgumentParser | None = None,
                    branches: list[tuple] | None = None, branch_key: str | None = None) -> dict:
    props, required, sub = _params(command, p)
    if branches is None and sub:
        branch_key = next(a.dest for a in _visible(p) if isinstance(a, argparse._SubParsersAction))
        branches = sub
    if dry is not None:
        dprops, _, _ = _params(command, dry)
        props[DRY_RUN] = {"type": "boolean", "default": False,
                          "description": "the loop on synthetic numbers, with no GPU and no agent (arbor run "
                                         "--dry-run); it takes seed, and its own defaults for max_iters and "
                                         "cooldown"}
        for k in dprops:
            if k not in props:
                props[k] = dict(dprops[k], description=dprops[k].get("description", "") + " (with dry_run: true)")
    s: dict = {"title": f"python3 -m {'arbor.directions' if command == 'directions' else 'arbor ' + command}",
               "type": "object"}
    if branches:
        all_sub = sorted({k for _, sp, _ in branches for k in sp})
        for k in all_sub:
            defs = [(name, sp[k]) for name, sp, _ in branches if k in sp]
            merged = dict(defs[0][1])
            if len({d.get("description", "") for _, d in defs}) > 1:   # one key, a meaning per action: say each
                merged["description"] = "; ".join(f"{name}: {d.get('description', '')}" for name, d in defs)
            props.setdefault(k, merged)
        s["oneOf"] = []
        for name, sp, req in branches:
            others = [k for k in all_sub if k not in sp]
            branch = {"properties": {branch_key: {"const": name}}, "required": [branch_key, *req]}
            if others:
                branch["not"] = {"anyOf": [{"required": [k]} for k in others]}
            s["oneOf"].append(branch)
    if dry is not None:
        only_dry = [k for k in props if k not in _params(command, p)[0] and k != DRY_RUN]
        s["allOf"] = [{"if": {"not": {"properties": {DRY_RUN: {"const": True}}, "required": [DRY_RUN]}},
                       "then": {"not": {"anyOf": [{"required": [k]} for k in only_dry]}}}]
    s["properties"] = {VERSION_KEY: {"const": VERSION}, COMMAND_KEY: {"const": command}, **props}
    s["required"] = required
    s["additionalProperties"] = False
    return s


def schema() -> dict:
    """The JSON Schema (draft 2020-12) of every command's payload, from the commands' own parsers."""
    defs = {}
    for command in COMMANDS:
        if command == "run":
            defs[command] = _command_schema(command, parser("run"), dry=parser("run", dry_run=True))
        elif command == "directions":
            branches = []
            for action in DIRECTIONS_ACTIONS:
                props, req, _ = _params(command, parser(command, action=action))
                branches.append((action, props, req))
            p = argparse.ArgumentParser(add_help=False)
            p.add_argument("action", choices=DIRECTIONS_ACTIONS, help="generate a map from a host's root profile, "
                                                                     "or split one map into shares")
            defs[command] = _command_schema(command, p, branches=branches, branch_key="action")
        else:
            defs[command] = _command_schema(command, parser(command))
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": SCHEMA_ID,
        "title": f"Arbor command payload, version {VERSION}",
        "description": ("The parameters of one Arbor command, as a JSON or YAML document: `python3 -m arbor "
                        "<command> --payload FILE`, or `python3 -m arbor --payload FILE` with `command` set "
                        "(`python3 -m arbor.directions --payload FILE` for directions). Each key is the flag's "
                        "long name with `_` for `-`. Generated from Arbor's parsers (arbor/cli/payload.py)."),
        "type": "object",
        "required": [VERSION_KEY],
        "properties": {VERSION_KEY: {"const": VERSION, "description": "the payload format's version"},
                       COMMAND_KEY: {"enum": list(COMMANDS),
                                     "description": "the command; may be left out when the command line names it"}},
        "oneOf": [{"$ref": f"#/$defs/{c}"} for c in COMMANDS],
        "$defs": defs,
    }


def markdown(s: dict | None = None) -> str:
    """The schema as one table per command: what ``docs/cli.md`` carries below its marker."""
    s = s or schema()
    flags: dict[tuple[str, str], list[str]] = {}
    for command in COMMANDS:
        ps = [parser(command, action=a) for a in DIRECTIONS_ACTIONS] if command == "directions" else (
            [parser("run"), parser("run", dry_run=True)] if command == "run" else [parser(command)])
        stack = list(ps)
        while stack:
            p = stack.pop(0)
            for a in _visible(p):
                if isinstance(a, argparse._SubParsersAction):
                    stack += list(a.choices.values())
                elif a.option_strings:
                    flags.setdefault((command, a.dest), [])
                    if _long(a) not in flags[(command, a.dest)]:
                        flags[(command, a.dest)].append(_long(a))
    flags[("run", DRY_RUN)] = ["--dry-run"]
    out = []
    for command in COMMANDS:
        d = s["$defs"][command]
        out += [f"### `{command}`", "", f"`{d['title']}`", "",
                "| Key | Flag | Type | Default | Required | Meaning |", "| --- | --- | --- | --- | --- | --- |"]
        for key, ps in d["properties"].items():
            if key in (VERSION_KEY, COMMAND_KEY):
                continue
            t = ps.get("type", "string")
            t = " or ".join(t) if isinstance(t, list) else t
            if "enum" in ps:
                t = " \\| ".join(f"`{c}`" for c in ps["enum"])
            if "default" in ps:
                default = f"`{ps['default'] if isinstance(ps['default'], str) else json.dumps(ps['default'])}`"
            else:
                default = ps.get("$comment", "").replace("default: ", "")
            req = "yes" if key in d["required"] else ""
            if not req and "oneOf" in d:
                need = [b["properties"][next(iter(b["properties"]))]["const"] for b in d["oneOf"]
                        if key in b["required"]]
                req = f"for {', '.join(need)}" if need else ""
            flag = " / ".join(f"`{f}`" for f in flags.get((command, key), [])) or "(positional)"
            meaning = ps.get("description", "").replace("|", "\\|")
            out.append(f"| `{key}` | {flag} | {t} | {default} | {req} | {meaning} |")
        out.append("")
    return "\n".join(out)


def write(root: Path = ROOT) -> list[Path]:
    """Regenerate the checked-in schema and ``docs/cli.md``'s tables; the files that changed."""
    changed = []
    s = schema()
    text = json.dumps(s, indent=2) + "\n"
    target = root / SCHEMA_FILE.relative_to(ROOT)
    target.parent.mkdir(parents=True, exist_ok=True)
    if not target.is_file() or target.read_text() != text:
        target.write_text(text)
        changed.append(target)
    doc = root / DOC_FILE.relative_to(ROOT)
    head = doc.read_text().split(DOC_BEGIN)[0] if doc.is_file() else ""
    body = f"{head.rstrip()}\n\n{DOC_BEGIN}\n\n{markdown(s)}"
    if not doc.is_file() or doc.read_text() != body:
        doc.write_text(body)
        changed.append(doc)
    return changed


def main(argv: list[str] | None = None) -> int:
    """``python3 -m arbor schema [<command>] [--markdown] [--write]``."""
    ap = argparse.ArgumentParser(prog="python3 -m arbor schema",
                                 description="The JSON Schema of each command's --payload (arbor/cli/payload.py).")
    ap.add_argument("command", nargs="?", choices=COMMANDS, help="one command's schema; every command's without")
    ap.add_argument("--markdown", action="store_true", help="the tables docs/cli.md carries, not JSON")
    ap.add_argument("--write", action="store_true",
                    help="regenerate docs/schema/arbor-cli-payload.schema.json and docs/cli.md's tables")
    args = ap.parse_args(argv)
    if args.write:
        for path in write():
            print(f"wrote {path.relative_to(ROOT)}")
        return 0
    s = schema()
    if args.markdown:
        print(markdown(s))
    elif args.command:
        print(json.dumps(s["$defs"][args.command], indent=2))
    else:
        print(json.dumps(s, indent=2))
    return 0
