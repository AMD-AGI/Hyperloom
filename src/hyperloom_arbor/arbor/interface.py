def contract() -> dict:
    """The contract, as ``interface --json`` prints it."""
    from arbor import component, lifecycle, objective, roles, triggers, version
    from arbor.cli import payload

    fired = set(triggers.FIRED)
    host_records = [
        (component.EXIT_FILE, EXIT_SCHEMA, "exit", "the run ends", [component.COMPONENT]),
        (component.REFUSED_FILE, REFUSED_SCHEMA, "refused", "a start is refused", [component.COMPONENT]),
        (component.HEARTBEAT_FILE, HEARTBEAT_SCHEMA, "heartbeat",
         f"every {component.HEARTBEAT_S} s, and at each phase", [component.COMPONENT]),
        (lifecycle.JOURNAL, EVENT_SCHEMA, "event", "each entry, one a line", list(component.MODES)),
        (f"{component.OUTBOX}/NNNN/{component.KEEP_FILE}", KEEP_SCHEMA, "keep",
         f"each KEEP; {component.OUTBOX}/{component.LATEST} names the newest", [component.COMPONENT]),
    ]
    other_records = [
        (roles.ORDER_FILE, roles.ORDER_SCHEMA, "the master hands a stretch to a worker"),
        (roles.REPORT_FILE, roles.REPORT_SCHEMA, "a worker's stretch ends"),
        (roles.EXIT_FILE, roles.EXIT_SCHEMA, "a master or worker command ends"),
        (objective.FILE, None, "every start: what the campaign optimizes"),
        (payload.RECORD, None, "every start: how it was asked for"),
    ]
    return {
        "interface": ID,
        "arbor": version.provenance(),
        "interfaces": dict(version.INTERFACES),
        "channels": dict(CHANNELS),
        "commands": list(version.COMMANDS),
        "config": {"modes": list(component.MODES), "component_keys": list(component.BLOCK_KEYS)},
        "outcomes": dict(OUTCOMES),
        "exit": exit_table(),
        "exit_codes": exit_codes(),
        "journal": {"file": lifecycle.JOURNAL, "schema": EVENT_SCHEMA, "kinds": list(lifecycle.KINDS)},
        "events": [{"name": name, "when": when, "fires": name in fired} for name, when in lifecycle.EVENTS],
        "records": ([{"file": f, "schema": s, "schema_file": f"docs/schema/host/{n}.schema.json", "written": w,
                      "modes": m} for f, s, n, w, m in host_records]
                    + [{"file": f, "schema": s, "schema_file": None, "written": w, "modes": list(component.MODES)}
                       for f, s, w in other_records]),
        "timing": timing(),
    }


def timing() -> dict:
    """The numbers a host plans by, from the code's constants."""
    from arbor import component, conflicts, review, triggers
    from arbor.cluster import handoff

    est = {k: handoff.DEFAULTS[k] for k in ("est_default_min", "est_floor_min", "est_window", "est_quantile",
                                            "est_factor")}
    return {
        "deadline_margin_s": component.DEADLINE_MARGIN_S,
        "heartbeat_s": component.HEARTBEAT_S,
        "sigterm_exit_s": component.SIGTERM_EXIT_S,
        "sigterm_server_wait_s": component.SIGTERM_SERVER_WAIT_S,
        "component_phase_minutes": dict(component.PHASE_MINUTES),
        "standalone_turn_minutes": dict(component.STANDALONE_TURN_MINUTES),
        "declared_bench_margin_min": component.DECLARED_MARGIN_MIN,
        "iteration_estimate": est,
        "review_poll_s": review.POLL_S,
        "conflicts_poll_s": conflicts.POLL_S,
        "blocking_trigger_s": triggers.BLOCKING_TIMEOUT_S,
    }


def fingerprint(doc: dict | None = None) -> str:
    """The contract's fingerprint: sha256 of its canonical JSON, without ``arbor`` (the Arbor that printed it)."""
    doc = dict(contract() if doc is None else doc)
    doc.pop("arbor", None)
    return hashlib.sha256(json.dumps(doc, sort_keys=True, separators=(",", ":")).encode()).hexdigest()[:16]


# ── a JSON Schema subset, for the records ─────────────────────────────────────

_TYPES = {"object": dict, "array": list, "string": str, "boolean": bool, "null": type(None)}


def _is(value, kind: str) -> bool:
    if kind == "integer":
        return isinstance(value, int) and not isinstance(value, bool)
    if kind == "number":
        return isinstance(value, (int, float)) and not isinstance(value, bool)
    return isinstance(value, _TYPES[kind])


def validate(doc, schema: dict, where: str = "$") -> list[str]:
    """What is wrong with ``doc`` against ``schema``: ``type``, ``enum``, ``const``, ``required``, ``properties``,
    ``additionalProperties`` (false or a schema), ``items`` and ``minItems``, the subset the host schemas use."""
    errors: list[str] = []
    kinds = schema.get("type")
    if kinds is not None:
        kinds = [kinds] if isinstance(kinds, str) else kinds
        if not any(_is(doc, k) for k in kinds):
            return [f"{where}: {type(doc).__name__} where the schema takes {' or '.join(kinds)}"]
    if "const" in schema and doc != schema["const"]:
        errors.append(f"{where}: {doc!r}, not {schema['const']!r}")
    if "enum" in schema and doc not in schema["enum"]:
        errors.append(f"{where}: {doc!r} is not one of {schema['enum']}")
    if isinstance(doc, dict):
        props = schema.get("properties") or {}
        for key in schema.get("required") or []:
            if key not in doc:
                errors.append(f"{where}: no `{key}`")
        extra = schema.get("additionalProperties", True)
        for key, value in doc.items():
            if key in props:
                errors += validate(value, props[key], f"{where}.{key}")
            elif extra is False:
                errors.append(f"{where}: `{key}` is not in the schema")
            elif isinstance(extra, dict):
                errors += validate(value, extra, f"{where}.{key}")
    if isinstance(doc, list):
        if len(doc) < schema.get("minItems", 0):
            errors.append(f"{where}: fewer than {schema['minItems']} items")
        if isinstance(schema.get("items"), dict):
            for i, item in enumerate(doc):
                errors += validate(item, schema["items"], f"{where}[{i}]")
    return errors


def schema(name: str) -> dict:
    """A host record's schema, ``name`` one of ``SCHEMAS``."""
    return json.loads((SCHEMA_DIR / f"{name}.schema.json").read_text())


def check_record(name: str, doc) -> list[str]:
    """What is wrong with a host record ``doc`` (``name`` one of ``SCHEMAS``)."""
    return validate(doc, schema(name))


# ── docs/interface.md ─────────────────────────────────────────────────────────

def _cell(value) -> str:
    if value is None:
        return "-"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (list, tuple)):
        return ", ".join(str(v) for v in value) or "-"
    return str(value).replace("|", "\\|")


def markdown(doc: dict | None = None) -> str:
    """The contract as the tables ``docs/interface.md`` carries below its marker."""
    doc = contract() if doc is None else doc
    out = [f"## The contract: `{doc['interface']}`", "",
           f"Fingerprint `{fingerprint(doc)}`. The per-part versions beside it (`version --json`): "
           + ", ".join(f"{k} {v}" for k, v in doc["interfaces"].items()) + ".", "",
           "### The channels", "", "| Channel | Today |", "| --- | --- |"]
    out += [f"| {k} | {_cell(v)} |" for k, v in doc["channels"].items()]
    out += ["", "### How a run ends", "", "| Outcome | Means |", "| --- | --- |"]
    out += [f"| `{k}` | {_cell(v)} |" for k, v in doc["outcomes"].items()]
    out += ["", "| End | Code | Outcome | Resumable | Record | A host should |", "| --- | --- | --- | --- | --- | --- |"]
    out += [f"| `{e['end']}` | {_cell(e['code']) if e['code'] is not None else 'any other'} | `{e['outcome']}` | "
            f"{_cell(e['resumable'])} | {_cell(e['record'])} | {_cell(e['host'])} |" for e in doc["exit"]]
    j = doc["journal"]
    out += ["", "### Events", "", f"Journal: `{j['file']}` (`{j['schema']}`), entries of kind "
            + ", ".join(f"`{k}`" for k in j["kinds"]) + ".", "", "| Event | When | Fires |", "| --- | --- | --- |"]
    out += [f"| `{e['name']}` | {_cell(e['when'])} | {_cell(e['fires'])} |" for e in doc["events"]]
    out += ["", "### Records", "", "| File | Schema | Schema file | Written | Modes |", "| --- | --- | --- | --- | --- |"]
    out += [f"| `{r['file']}` | {_cell(r['schema'])} | {_cell(r['schema_file'])} | {_cell(r['written'])} | "
            f"{_cell(r['modes'])} |" for r in doc["records"]]
    out += ["", "### Timing", "", "| Name | Value |", "| --- | --- |"]
    for k, v in doc["timing"].items():
        out.append(f"| `{k}` | {_cell(json.dumps(v) if isinstance(v, dict) else v)} |")
    out += ["", "### The component block's keys", "", ", ".join(f"`{k}`" for k in doc["config"]["component_keys"])]
    return "\n".join(out) + "\n"


def write(root: Path = ROOT) -> list[Path]:
    """Regenerate ``docs/interface.md``'s tables; the files that changed."""
    doc = root / DOC_FILE.relative_to(ROOT)
    head = doc.read_text().split(DOC_BEGIN)[0] if doc.is_file() else "# Arbor's host interface\n"
    body = f"{head.rstrip()}\n\n{DOC_BEGIN}\n\n{markdown()}"
    if doc.is_file() and doc.read_text() == body:
        return []
    doc.write_text(body)
    return [doc]


def parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="python3 -m arbor interface",
                                description="Arbor's host interface: the contract a launcher or a host reads.")
    p.add_argument("--json", action="store_true", help="the contract as JSON")
    p.add_argument("--markdown", action="store_true", help="the tables docs/interface.md carries")
    p.add_argument("--write", action="store_true", help="regenerate docs/interface.md's tables")
    p.add_argument("--check", metavar="FILE", help="check a host record against its schema: exit 1 when it fails")
    return p


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    if args.write:
        for path in write():
            print(f"wrote {path.relative_to(ROOT)}")
        return 0
    if args.check:
        doc = json.loads(Path(args.check).read_text())
        name = next((n for n, s in SCHEMAS.items() if doc.get("schema") == s), None) if isinstance(doc, dict) else None
        if name is None:
            print(f"{args.check}: no `schema` this Arbor knows ({', '.join(SCHEMAS.values())})", file=sys.stderr)
            return 1
        errors = check_record(name, doc)
        for e in errors:
            print(f"{args.check}: {e}", file=sys.stderr)
        return 1 if errors else 0
    if args.markdown:
        print(markdown(), end="")
        return 0
    if args.json:
        print(json.dumps(contract(), indent=2))
        return 0
    print(f"{ID} ({fingerprint()}): python3 -m arbor interface --json")
    return 0


if __name__ == "__main__":
    sys.exit(main())
