"""Arbor's host interface, ``arbor.host``: one contract, generated from the code.

A launcher or a host (a scheduler, a cluster job, a host that runs Arbor as one of its components) depends on what
Arbor takes at its start, what it writes while it runs, and how it ends. ``python3 -m arbor interface --json`` prints
that contract, built from the constants the code itself uses, so it cannot drift from what runs:

- ``channels``: the five ways a launcher and Arbor talk: the start, messages in, events out, results out, the end;
- ``commands`` and ``config``: what a launcher starts, and the component block's keys;
- ``exit``: every way a run ends, with its exit code, its ``outcome`` (``OUTCOMES``: what kind of end it is), whether
  starting the same command again can help (``resumable``), the record that says so, and what a host should do;
- ``events`` and ``journal``: the lifecycle's events, the ones that fire, and the journal they are written to;
- ``records``: each file Arbor writes for others, with its schema id and, for the host's records, its JSON Schema in
  ``docs/schema/host/``;
- ``timing``: what a host plans by: the deadline's margin, the heartbeat, SIGTERM's grace, the phase caps, the
  iteration estimate;
- ``interfaces``: ``version --json``'s per-part versions, beside it.

``docs/interface.md`` is rendered from it: ``python3 -m arbor interface --write``.

The contract's version is semver (``VERSION``). An additive change raises the minor, a breaking one the major.
``FINGERPRINTS`` holds each version's fingerprint, and a test fails when the contract changes and its version does
not. Version 1 is the interface hosts integrated against before it was published (``version --json``'s ``component``
1 to 5); 2.0 publishes it as it is, every host record now carrying its schema id and the Arbor that wrote it. 2.1
adds ``run --exit-at-handover`` (a host deals each worker report), the booking of an iteration a crash left at the
next start, and a group's umask on a group's session directory. 2.2: one driver per session, a second exits 73
(``lease_held``) once the session lock is still held after a minute.

The records validate with ``validate``, a JSON Schema subset in the standard library alone, so a host can check a
record without installing anything.
"""

