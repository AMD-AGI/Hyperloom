def exit_codes() -> dict[str, int]:
    """Every exit code a run ends with, by name (0: an ending the exit record names)."""
    from arbor import checkpoints, component
    from arbor.cluster import handoff
    return {"ended": 0, "refused": component.EXIT_REFUSED, "unreachable": component.EXIT_UNREACHABLE,
            "lease_held": handoff.EXIT_LEASE_HELD, "handed_off": handoff.EXIT_HANDOFF,
            "paused": checkpoints.EXIT_PAUSED, "roll_config": handoff.EXIT_ROLL_CONFIG}


def exit_table() -> list[dict]:
    """``_EXIT`` with each code resolved, and where its record is written."""
    from arbor import component
    codes = exit_codes()
    files = {"exit": component.EXIT_FILE, "refused": component.REFUSED_FILE}
    out = []
    for end, code, outcome, resumable, rec, host in _EXIT:
        out.append({"end": end, "code": codes[code] if isinstance(code, str) else code,
                    "reason": end if end in component.REASONS else None, "outcome": outcome,
                    "resumable": resumable, "record": files.get(rec), "host": host})
    return out


